- LONG優勢でも、1分RSIが70以上なら新規成行ロングは禁止し、必ず「押し目買い待ち」とする
- SHORT優勢かつ1分RSI30以下では、confidenceを最大70点程度に抑える
- LONG優勢かつ1分RSI70以上では、confidenceを最大70点程度に抑える
